#!/usr/bin/env node
// Validates images.json against the documented schema (see SCHEMA.md).
//
// This runs in CI *before* the generated index is committed. If a change to
// the generator (or to a wallpaper file) would violate the published
// contract, this fails loudly instead of silently shipping a breaking change
// to every client that reads the index.
//
// It also checks that tags-index.json agrees with images.json, so the search
// index can never drift from the catalog it is built from.
//
// Exits 0 when valid, 1 when the contract is violated.

const fs = require("fs");

const INDEX_PATH = "images.json";
const TAGS_INDEX_PATH = "tags-index.json";

// Required on every wallpaper record. See SCHEMA.md.
const REQUIRED_STRING_FIELDS = ["id", "name", "category", "url", "thumbnail", "format"];
const REQUIRED_NUMBER_FIELDS = ["width", "height"];

function fail(message) {
  console.error(`\u2716 images.json contract violation: ${message}`);
  process.exit(1);
}

let data;
try {
  data = JSON.parse(fs.readFileSync(INDEX_PATH, "utf8"));
} catch (error) {
  fail(`not valid JSON (${error.message})`);
}

if (!Array.isArray(data)) {
  fail(`top level must be a flat array, got ${Array.isArray(data) ? "array" : typeof data}`);
}

if (data.length === 0) {
  fail("index is empty");
}

const seenIds = new Set();
const expectedTagCounts = new Map();

data.forEach((item, index) => {
  if (item === null || typeof item !== "object" || Array.isArray(item)) {
    fail(`item ${index} must be an object`);
  }

  for (const field of REQUIRED_STRING_FIELDS) {
    if (typeof item[field] !== "string" || item[field].length === 0) {
      fail(`item ${index} is missing required string field "${field}"`);
    }
  }

  for (const field of REQUIRED_NUMBER_FIELDS) {
    if (item[field] !== null && typeof item[field] !== "number") {
      fail(`item ${index} field "${field}" must be a number or null`);
    }
  }

  for (const field of ["url", "thumbnail"]) {
    const value = item[field];
    if (!/^https?:\/\//.test(value)) {
      fail(`item ${index} field "${field}" must be an absolute http(s) URL`);
    }
    // The URL must be safe to request as-is: no raw spaces or other
    // non-ASCII / control characters that would need client-side encoding.
    if (/[^\x21-\x7e]/.test(value)) {
      fail(`item ${index} field "${field}" contains unencoded characters: ${value}`);
    }
  }

  if (seenIds.has(item.id)) {
    fail(`duplicate id "${item.id}"`);
  }
  seenIds.add(item.id);

  // --- tags ---------------------------------------------------------------
  // Every record must be searchable, so every record carries at least one tag
  // (its category) even when the author has not added any of their own.
  if (!Array.isArray(item.tags) || item.tags.length === 0) {
    fail(`item ${index} ("${item.id}") must have a non-empty "tags" array`);
  }

  const seenTags = new Set();
  for (const tag of item.tags) {
    if (typeof tag !== "string" || tag.length === 0) {
      fail(`item ${index} ("${item.id}") has a non-string or empty tag`);
    }
    if (tag !== tag.trim().toLowerCase() || /\s{2,}/.test(tag)) {
      fail(`item ${index} ("${item.id}") has a tag that is not normalized: "${tag}"`);
    }
    if (tag.includes(",")) {
      fail(`item ${index} ("${item.id}") has a tag containing a comma: "${tag}"`);
    }
    if (seenTags.has(tag)) {
      fail(`item ${index} ("${item.id}") has duplicate tag "${tag}"`);
    }
    seenTags.add(tag);
    expectedTagCounts.set(tag, (expectedTagCounts.get(tag) || 0) + 1);
  }

  if (!seenTags.has(item.category)) {
    fail(`item ${index} ("${item.id}") tags must include its category "${item.category}"`);
  }

  // --- credit (optional) ---------------------------------------------------
  // Present when the image came from an external source; absent for
  // hand-added wallpapers. If present, it must be usable for attribution.
  if (item.credit !== undefined) {
    if (item.credit === null || typeof item.credit !== "object" || Array.isArray(item.credit)) {
      fail(`item ${index} ("${item.id}") field "credit" must be an object when present`);
    }
    for (const field of ["author", "license", "source", "url"]) {
      if (item.credit[field] === undefined) continue;
      if (typeof item.credit[field] !== "string" || item.credit[field].length === 0) {
        fail(`item ${index} ("${item.id}") credit."${field}" must be a non-empty string`);
      }
    }
    if (item.credit.url && !/^https?:\/\//.test(item.credit.url)) {
      fail(`item ${index} ("${item.id}") credit.url must be an absolute http(s) URL`);
    }
  }
});

// --- tags-index.json agrees with images.json ------------------------------
if (!fs.existsSync(TAGS_INDEX_PATH)) {
  fail(`${TAGS_INDEX_PATH} is missing (it is generated by scripts/generate-images-json.js)`);
}

let tagsIndex;
try {
  tagsIndex = JSON.parse(fs.readFileSync(TAGS_INDEX_PATH, "utf8"));
} catch (error) {
  fail(`${TAGS_INDEX_PATH} is not valid JSON (${error.message})`);
}

if (!tagsIndex || !Array.isArray(tagsIndex.tags)) {
  fail(`${TAGS_INDEX_PATH} must be an object with a "tags" array`);
}

const indexedTags = new Map();
for (const entry of tagsIndex.tags) {
  if (!entry || typeof entry.tag !== "string" || typeof entry.count !== "number") {
    fail(`${TAGS_INDEX_PATH} has an entry without a string "tag" and numeric "count"`);
  }
  if (indexedTags.has(entry.tag)) {
    fail(`${TAGS_INDEX_PATH} lists tag "${entry.tag}" more than once`);
  }
  indexedTags.set(entry.tag, entry.count);
}

for (const [tag, count] of expectedTagCounts) {
  if (!indexedTags.has(tag)) {
    fail(`${TAGS_INDEX_PATH} is missing tag "${tag}" from images.json`);
  }
  if (indexedTags.get(tag) !== count) {
    fail(`${TAGS_INDEX_PATH} says tag "${tag}" appears ${indexedTags.get(tag)}x, images.json says ${count}x`);
  }
}

for (const tag of indexedTags.keys()) {
  if (!expectedTagCounts.has(tag)) {
    fail(`${TAGS_INDEX_PATH} lists tag "${tag}" which no wallpaper in images.json has`);
  }
}

console.log(
  `\u2714 images.json OK \u2014 ${data.length} wallpapers, ${seenIds.size} unique ids, ${expectedTagCounts.size} tags, schema v2`
);
console.log(`\u2714 ${TAGS_INDEX_PATH} OK \u2014 matches images.json`);
