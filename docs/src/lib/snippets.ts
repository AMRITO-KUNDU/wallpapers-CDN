export const JS_SNIPPET = `const INDEX =
  "${JSON_CDN_URL}";

const catalog = await fetch(INDEX).then((res) => res.json());

// Filter by tag...
const nebula = catalog.filter((item) => item.tags.includes("nebula"));

// ...or by category
const abstract = catalog.filter((item) => item.category === "abstract");

// Simple search across the name and every tag
const q = "dusk";
const results = catalog.filter((item) =>
  [item.name, ...item.tags].join(" ").toLowerCase().includes(q)
);
`;

export const FLUTTER_SNIPPET = `const indexUrl =
  '${JSON_CDN_URL}';

final response = await http.get(Uri.parse(indexUrl));
final catalog = jsonDecode(response.body) as List;

// tags is a List<String> on every record
final wallpaper = catalog.firstWhere(
  (item) => (item['tags'] as List).contains('nebula'),
  orElse: () => <String, dynamic>{},
);
`;

